function englishSingleUnit(kp) {
  if (/情景|交际|对话/.test(kp)) return "补全对话与交际";
  if (/时态|过去时|完成时|将来时|进行时|现在时|被动|语态/.test(kp)) return "语法·时态与语态";
  if (/从句|主谓一致|不定式|非谓语|动名词|分词|句型|such|so\/such|would rather|not\.\.\.until|had better|forget|There be|there be|ask sb|decide to|It is important|see sb|比较级, the|疑问句|并列谓语/.test(kp)) return "语法·句子与非谓语";
  return "语法·词法与固定搭配";
}

const CHINESE_LABEL_UNITS = [[/古诗/, "古诗词鉴赏"], [/文言/, "文言文阅读"], [/记叙|散文|小说|现代文/, "记叙文阅读"], [/说明/, "说明文阅读"], [/议论/, "议论文阅读"]];
function chineseByTitle(paper, title) {
  for (const s of paper.sections) for (const g of s.groups || []) {
    if (g.title === title) for (const [re, unit] of CHINESE_LABEL_UNITS) if (re.test(g.label || "")) return unit;
  }
  return "";
}

export function unitOf(paper, section, group, item) {
  if (paper.unit) return paper.unit; // 小升初衔接等按章出的练习，整套属于同一章
  const subject = paper.subject || "english";
  const kp = String(item?.kp || "").trim();
  const t = section.type;
  if (subject === "english") {
    if (t === "单项选择") return englishSingleUnit(kp);
    const unit = ENGLISH_SECTION_UNITS[t];
    if (!unit) throw new Error(`${paper.id}: 英语题型“${t}”没有对应的考点模块`);
    return unit;
  }
  if (subject === "chinese") {
    if (t === "古诗文默写") return "古诗文默写";
    if (group) {
      for (const [re, unit] of CHINESE_LABEL_UNITS) if (re.test(group.label || "")) return unit;
    }
    if (t === "回答问题") {
      const unit = chineseByTitle(paper, section.title);
      if (unit) return unit;
    }
    if (/名著|文学常识|文学文化常识/.test(kp) || /名著/.test(item?.stem || "")) return "名著与文学常识";
    if (/作文/.test(kp) || /作文/.test(item?.stem || "")) return "作文";
    if (t === "单项选择" || /字音|字形|成语|病句|标点|修辞|词语/.test(kp)) return "积累与运用";
    if (/古诗/.test(kp)) return "古诗词鉴赏";
    throw new Error(`${paper.id} 第 ${item?.n} 题：语文题没法确定考点模块（题型 ${t}，kp ${kp || "无"}）`);
  }
  const unit = lookup[subject]?.get(kp);
  if (!unit) throw new Error(`${paper.id} 第 ${item?.n} 题：${subject} 知识点“${kp}”不在章节表里，请在 tools/units.mjs 里补上`);
  return unit;
}
